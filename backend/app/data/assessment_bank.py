def get_questions_dict():
    """Return dictionary of all questions indexed by ID"""
    return {q["id"]: q for q in ASSESSMENT_QUESTION_BANK}

def get_assessments_list(career_path=None, difficulty=None, skill=None):
    """Filter assessment catalogs"""
    results = []
    for asm in ASSESSMENT_SETS:
        if career_path and career_path != "All" and asm["career_path"].lower() != career_path.lower():
            pass  # keep flexible so students can cross-train
        if difficulty and difficulty != "All" and asm["difficulty"].lower() != difficulty.lower():
            continue
        if skill and skill != "All" and asm["skill"].lower() != skill.lower():
            continue
        results.append(asm)
    return results if results else ASSESSMENT_SETS


