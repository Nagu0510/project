def get_all_career_paths():
    """Return all career path summaries"""
    paths = []
    for k, v in CAREER_PATHS_CONFIG.items():
        paths.append({
            "id": v["id"],
            "title": v["title"],
            "slug": v.get("slug", v["id"]),
            "description": v["description"],
            "match_percentage": v["match_percentage"],
            "required_skills": v["required_skills"],
            "average_salary": v["average_salary"],
            "active_openings": v["active_openings"],
            "top_companies": v["top_companies"],
            "difficulty": v["difficulty"],
            "demand_level": v.get("demand_level", "High Demand"),
        })
    return paths

def get_career_path_by_id_or_title(identifier: str):
    """Lookup career config by id or title"""
    clean = identifier.lower().strip()
    if clean in CAREER_PATHS_CONFIG:
        return CAREER_PATHS_CONFIG[clean]
    for k, v in CAREER_PATHS_CONFIG.items():
        if v["title"].lower() == clean or v.get("slug", "").lower() == clean:
            return v
        if clean in v["title"].lower() or clean in k:
            return v
    return CAREER_PATHS_CONFIG["backend"]
